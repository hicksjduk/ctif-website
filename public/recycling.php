<h1>Recycling</h1>
<h2><a id="foil">Aluminium foil</a></h2>
<p>The churches work together to collect foil, which is taken to the 
<a href="https://qe2activitycentre.co.uk/">Queen Elizabeth 2
Activity Centre</a> in 
<a href="https://www.hants.gov.uk/thingstodo/countryparks/rhcp">River Hamble Country Park</a> - 
they sell the foil for recycling, and raise money
for equipment. Foil is collected in various churches, and there are publicly-available bins
at Immaculate Conception Roman Catholic
church in Stubbington and Sacred Heart Roman Catholic church in Fareham. 
<p><b>Please</b> make sure that the foil is clean, and is actually foil not shiny plastic!
If in doubt, use the 'scrunch' test - scrunch it in your hand and release it, if it stays scrunched
it is probably aluminium, if it doesn't it definitely isn't.
<h2>Plastic milk bottle tops</h2>
<b>Please note that the collection of milk bottle tops is now closed</b>. Unfortunately
we no longer have anywhere to take them for recycling. Tops can still be recycled in
Fareham Borough Council blue-topped recycling bins, as long as they are screwed on to the 
bottle.
<h2>Other things</h2>
<p>Various churches in Fareham provide recycling facilities for items that are not
recycled by the council. Below are some details of which we have been notified.
<h3>Fareham United Reformed Church</h3>
<ul>
<li>Printer cartridges, taken to a local infant school
<li>Aluminium foil (see above)
<li>Toothbrushes, toothpaste, make-up tubes etc, taken to Eco-freaks in Lee on Solent.
<li>Used stamps for RNIB 
</ul>
<h3>St John's</h3>
<p>Used stamps, coins, spectacles, hearing aids, mobile phones, ink cartridges, aluminum foil. 
See <a href="https://stjohnsfareham.org.uk/recycling">the church's
recycling page</a> for more details.
<h3>Fareham Methodist Church</h3>
Unfortunately the Terracycle recycling scheme has now been discontinued.
